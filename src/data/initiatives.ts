/** 获取指定改革在树中的层级深度（无前置改革为 0） */
export function getInitiativeDepth(initiative: Initiative): number {
  if (!initiative.requiresInitiative || initiative.requiresInitiative.length === 0) return 0
  let depth = 0
  let current: Initiative | undefined = initiative
  const visited = new Set<string>()
  while (current?.requiresInitiative && current.requiresInitiative.length > 0) {
    const parentId = current.requiresInitiative[0]
    if (visited.has(parentId)) break // 防止循环
    visited.add(parentId)
    current = INITIATIVES.find((i) => i.id === parentId)
    if (!current) break
    depth++
  }
  return depth
}

/** 获取解锁指定政策的改革列表（用于政策树 UI 反向展示） */
export function getInitiativesUnlockingPolicy(policyId: string): Initiative[] {
  return INITIATIVES.filter((i) => i.unlocksPolicies?.includes(policyId))
}